    #[test]
    fn auto_play_follows_transitions() {
        let mut s = state();
        let a = video(&mut s);
        let b = video(&mut s);
        // b goes to Program: it starts playing; a leaves at the end: it is paused.
        s.apply(&Command::Play { input: a }).unwrap();
        let io = s.apply(&Command::Transition { button: 1 }).unwrap();
        assert_eq!(io, [IoRequest::Play { input: b }]);
        let id = s.transition.unwrap().id();
        let io = s.apply_event(&Event::TransitionDone { id });
        assert_eq!(io, [IoRequest::Pause { input: a }]);
        assert!(s.input(b).unwrap().playback.unwrap().playing);
        assert!(!s.input(a).unwrap().playback.unwrap().playing);

        // With restart: a seek to 0 before playing; Cut applies the same rules.
        s.apply(&Command::SetAutoPlay(AutoPlay {
            play_on_transition: true,
            restart_on_transition: true,
            pause_after_transition: false,
        }))
        .unwrap();
        let io = s.apply(&Command::Cut).unwrap();
        assert_eq!(
            io,
            [
                IoRequest::Seek { input: a, ms: 0 },
                IoRequest::Play { input: a }
            ]
        );
        assert!(
            s.input(b).unwrap().playback.unwrap().playing,
            "no auto-pause"
        );

        // Everything off: transitions leave playback alone.
        s.apply(&Command::SetAutoPlay(AutoPlay {
            play_on_transition: false,
            restart_on_transition: false,
            pause_after_transition: false,
        }))
        .unwrap();
        s.apply(&Command::Pause { input: b }).unwrap();
        assert!(s.apply(&Command::Cut).unwrap().is_empty());
    }

