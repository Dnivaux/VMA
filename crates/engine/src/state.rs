/// Life cycle of an output (`phase-2.md` § 5).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub enum OutputStatus {
    Idle,
    /// Asked to `io-gst`, not confirmed yet.
    Starting,
    /// `encoder`: the encoders retained (and why a fallback, if any; empty for the full
    /// screen); `target`: the file of a recording, the screen of the full screen.
    Running {
        encoder: String,
        target: Option<String>,
    },
    /// A stream lost its server (or could not reach it) and is being reconnected: attempt
    /// `attempt` comes after 1, 2, 5, then every 10 s; `reason` of the last loss.
    Reconnecting {
        attempt: u32,
        reason: String,
    },
    /// Finalising (end of stream, file closed).
    Stopping,
    /// Stopped by an error; the rest of the program carries on.
    Failed {
        reason: String,
    },
}

impl OutputStatus {
    /// Starting, running, reconnecting or stopping: its settings cannot change.
    pub fn is_active(&self) -> bool {
        !matches!(self, Self::Idle | Self::Failed { .. })
    }

    /// Produces (or tries to): starting, running or reconnecting.
    pub fn is_on(&self) -> bool {
        matches!(
            self,
            Self::Starting | Self::Running { .. } | Self::Reconnecting { .. }
        )
    }
}

