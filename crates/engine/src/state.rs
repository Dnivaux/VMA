    #[test]
    fn t_bar() {
        let mut s = state();
        let a = color(&mut s, 1);
        let b = color(&mut s, 2);
        let v = s.version;
        s.apply(&Command::SetFader { value: 0 }).unwrap();
        assert_eq!(s.version, v, "0 with no transition: nothing");
        s.apply(&Command::SetFader { value: 128 }).unwrap();
        assert_eq!(s.fader(), 128);
        assert!(matches!(
            s.transition,
            Some(TransitionState::Fader { from: Some(f), to, effect: Effect::Fade, .. }) if f == a && to == b
        ));
        assert_eq!(
            refused(&mut s, Command::Transition { button: 1 }),
            Rejection::TransitionRunning
        );
        // Released half-way: stays mixed.
        assert_eq!(s.program, Some(a));
        // Back to 0: abandoned.
        s.apply(&Command::SetFader { value: 0 }).unwrap();
        assert_eq!(
            (s.program, s.preview, s.transition),
            (Some(a), Some(b), None)
        );
        // All the way: swap, and the T-Bar reads 0 again.
        s.apply(&Command::SetFader { value: 200 }).unwrap();
        s.apply(&Command::SetFader { value: 255 }).unwrap();
        assert_eq!(
            (s.program, s.preview, s.transition),
            (Some(b), Some(a), None)
        );
        assert_eq!(s.fader(), 0);
        // Straight to 255 from idle also completes.
        s.apply(&Command::SetFader { value: 255 }).unwrap();
        assert_eq!(
            (s.program, s.preview, s.transition),
            (Some(a), Some(b), None)
        );
        // Refused during a timed transition.
        s.apply(&Command::Transition { button: 1 }).unwrap();
        assert_eq!(
            refused(&mut s, Command::SetFader { value: 50 }),
            Rejection::TransitionRunning
        );
    }

